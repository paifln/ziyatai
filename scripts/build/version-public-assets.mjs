import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { basename, extname } from "node:path";
import { format } from "prettier";
const check = process.argv.includes("--check");
await mkdir("public/assets", { recursive: true });
async function version(path) {
  const data = await readFile(path),
    ext = extname(path),
    stem = basename(path, ext);
  const name = `${stem}.${createHash("sha256").update(data).digest("hex").slice(0, 12)}${ext}`;
  const target = `public/assets/${name}`;
  if (check) {
    if (!(await readFile(target).catch(() => Buffer.alloc(0))).equals(data))
      throw new Error("Versioned assets are stale; run npm run build:lite");
  } else await writeFile(target, data);
  return `/assets/${name}`;
}
let html = await readFile("public/lite/index.html", "utf8");
for (const name of [
  "theme.js",
  "draft-merge.js",
  "drafts.js",
  "curriculum.js",
  "account-session.js",
  "lite.js",
  "lite.css",
]) {
  const url = await version(`public/lite/${name}`),
    ext = extname(name),
    stem = basename(name, ext);
  html = html
    .replaceAll(`/lite/${name}`, url)
    .replace(
      new RegExp(
        `/assets/${stem.replaceAll("-", "\\-")}\\.[a-f0-9]{12}\\${ext}`,
        "g",
      ),
      url,
    );
}
const font = await version("public/fonts/onest.woff2");
const manifest = JSON.stringify({ font }, null, 2) + "\n";
const css = await format(
  `/* Generated by build:lite. */\n@font-face { font-family: "Onest"; src: url("${font}") format("woff2"); font-weight: 100 900; font-style: normal; font-display: swap; }\n`,
  { parser: "css" },
);
if (check) {
  if (
    (await readFile("public/lite/index.html", "utf8")) !== html ||
    (await readFile("app/font.generated.css", "utf8").catch(() => "")) !==
      css ||
    (await readFile("app/public-assets.generated.json", "utf8").catch(
      () => "",
    )) !== manifest
  )
    throw new Error("Versioned asset references are stale");
} else {
  await writeFile("public/lite/index.html", html);
  await writeFile("app/font.generated.css", css);
  await writeFile("app/public-assets.generated.json", manifest);
}
